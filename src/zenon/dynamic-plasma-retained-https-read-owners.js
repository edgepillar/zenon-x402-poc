import { types as utilTypes } from 'node:util';
import { createBoundedJsonRpcHttpsExchangeOwner } from './bounded-json-rpc-https-exchange-owner.js';
import { createDynamicPlasmaJsonRpcReadTransport } from './dynamic-plasma-json-rpc-read-transport.js';
import { createRetainedAccountStateExchangeGate } from './dynamic-plasma-retained-account-exchange-gate.js';
import { selectBoundedJsonRpcReadAdmissionProfile } from './bounded-json-rpc-read-admission.js';

const OWNER = createBoundedJsonRpcHttpsExchangeOwner, WIRE = createDynamicPlasmaJsonRpcReadTransport;
const GATE = createRetainedAccountStateExchangeGate, PROFILE = selectBoundedJsonRpcReadAdmissionProfile;
const FREEZE = Object.freeze, CREATE = Object.create, DEFINE = Object.defineProperty;
const DESCRIPTOR = Object.getOwnPropertyDescriptor, PROTOTYPE = Object.getPrototypeOf;
const KEYS = Reflect.ownKeys, HAS = Object.hasOwn, IS_PROXY = utilTypes.isProxy;
const OBJECT = Object.prototype, ErrorType = TypeError;
const IS_FROZEN = Object.isFrozen;
const DP = 'dynamic_plasma_retained_candidate', ACCOUNT = 'zenon_account_state_retained_candidate';

/**
 * SOURCE implementation, not native qualification. Explicit contextv7 DP
 * endpoint owner: 78 requests, including six maximal eight-page spork cycles.
 * Construct two distinct owners for the two collector endpoints; never share
 * one counter or recreate an exhausted owner to continue the same attempt.
 * Existing public owner factories stay on their legacy thirteen-request mode.
 */
export function createRetainedDynamicPlasmaHttpsReadTransportOwner(options) {
  return retainedOwner(options, arguments.length, DP, false);
}

/** Explicit source-only V2 additionally retains the actual native inspector. */
export function createRetainedDynamicPlasmaHttpsReadTransportOwnerV2(options) {
  return retainedOwner(options, arguments.length, DP, true);
}

function retainedOwner(options, argumentCount, profileName, nativeCustody) {
  let inspector = null;
  const receive = FREEZE(function receive(inspect) {
    if (arguments.length !== 1 || inspector !== null || typeof inspect !== 'function'
        || IS_PROXY(inspect) || PROTOTYPE(inspect) !== Function.prototype || !IS_FROZEN(inspect)) reject();
    inspector = inspect;
  });
  const owner = nativeCustody
    ? OWNER(options, argumentCount, snapshotConfiguration, profileName, undefined, receive)
    : OWNER(options, argumentCount, snapshotConfiguration, profileName);
  if (nativeCustody && inspector === null) reject();
  let methods;
  if (profileName === ACCOUNT) {
    const gate = GATE(owner);
    methods = { exchange: gate.exchange, close: gate.close, requestBudget: PROFILE(ACCOUNT) };
  } else {
    const transport = WIRE(FREEZE({ exchange: owner.exchange }));
    methods = { transport, close: owner.close, requestBudget: PROFILE(DP) };
  }
  if (nativeCustody) methods.inspectNativeCustody = inspector;
  return FREEZE(methods);
}

/**
 * The corresponding eighteen-request account bracket. Supply exchange as the
 * real retained preparer's accountExchange. The closed gate forwards original
 * generated bytes only; the actual native owner enforces the same count.
 * These owners retain TLS/route/time/grace/uncertain-close checks. Neither
 * public constructor opens a connection; selected exchange calls really can.
 * Caller separately owns all three closes and preserves any uncertain native
 * outcome. No bundle close, native drain proof, wallet, SDK, signing, funding,
 * default buyer change or permission to execute is inferred from these DATA
 * request budgets. Real native qualification remains separately gated.
 */
export function createRetainedAccountStateHttpsExchangeOwner(options) {
  return retainedOwner(options, arguments.length, ACCOUNT, false);
}

/** Same account byte gate and budget, plus a private actual-native view. */
export function createRetainedAccountStateHttpsExchangeOwnerV2(options) {
  return retainedOwner(options, arguments.length, ACCOUNT, true);
}

function exact(value, fields) {
  if (typeof value !== 'object' || value === null || IS_PROXY(value) || PROTOTYPE(value) !== OBJECT
      || !IS_FROZEN(value) || KEYS(value).length !== fields.length) reject();
  const out = CREATE(null);
  for (let index = 0; index < fields.length; index++) {
    const name = fields[index];
    const d = DESCRIPTOR(value, name);
    if (!d || d.enumerable !== true || !HAS(d, 'value')) reject();
    put(out, name, d.value);
  }
  return FREEZE(out);
}
function snapshotConfiguration(options) {
  const top = exact(options, ['route', 'timeoutMs', 'closeGraceMs']);
  const route = exact(top.route, ['hostname', 'path', 'ipv4Address']);
  const out = CREATE(null);
  put(out, 'route', route); put(out, 'timeoutMs', top.timeoutMs); put(out, 'closeGraceMs', top.closeGraceMs);
  // The actual native core independently enforces the unchanged strict public
  // hostname/path/pinned-public-IPv4/timing grammar on these same DATA bytes.
  return FREEZE(out);
}
function reject() {
  const code = 'retained_https_read_owner_configuration_rejected', error = new ErrorType(code);
  put(error, 'code', code);
  const stack = CREATE(null); stack.value = 'TypeError: ' + code;
  DEFINE(error, 'stack', stack); throw FREEZE(error);
}
function put(target, name, value) {
  const d = CREATE(null); d.value = value; d.enumerable = true; DEFINE(target, name, d);
}
